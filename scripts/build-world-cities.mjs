/**
 * LIFE SCORE - builds the world city list and the country table from GeoNames.
 *
 * John, 4 Oct 2026: "go from comparing any of 200 given cities to being able to
 * compare any 2 cities in the world" - "Both": this built-in list, plus a live
 * Google place search for anything not on it (api/places/autocomplete.ts).
 *
 * Source: GeoNames (https://www.geonames.org), licensed CC BY 4.0 - the city
 * picker credits it. Every place of 15,000 people or more (cities15000), less
 * city districts (PPLX) and historical, abandoned or destroyed places (PPLH,
 * PPLQ, PPLW, PPLCH).
 *
 * Refresh:
 *   curl -O https://download.geonames.org/export/dump/cities15000.zip   (then unzip it)
 *   curl -O https://download.geonames.org/export/dump/countryInfo.txt
 *   curl -O https://download.geonames.org/export/dump/admin1CodesASCII.txt
 *   node scripts/build-world-cities.mjs <folder holding the three files>
 *
 * Writes public/data/world-cities.json (loaded by the picker when someone
 * searches) and src/data/countries.ts (country names and codes, for flags).
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/build-world-cities.mjs <folder with cities15000.txt, countryInfo.txt, admin1CodesASCII.txt>');
  process.exit(1);
}

const SKIPPED_KINDS = new Set(['PPLX', 'PPLH', 'PPLQ', 'PPLW', 'PPLCH']);

// Countries: ISO2 -> English name
const countries = {};
for (const line of readFileSync(join(dir, 'countryInfo.txt'), 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const cols = line.split('\t');
  if (cols[0] && cols[4]) countries[cols[0]] = cols[4];
}

// Regions: "US.FL" -> "Florida"
const regions = {};
for (const line of readFileSync(join(dir, 'admin1CodesASCII.txt'), 'utf8').split('\n')) {
  const cols = line.split('\t');
  if (cols[0] && cols[1]) regions[cols[0]] = cols[1];
}

// Cities: [name, region, countryCode, population, asciiName?]
const rows = [];
for (const line of readFileSync(join(dir, 'cities15000.txt'), 'utf8').split('\n')) {
  const cols = line.split('\t');
  if (cols.length < 15) continue;
  const [, name, ascii] = cols;
  const kind = cols[7];
  const cc = cols[8];
  const population = Number(cols[14]) || 0;
  if (SKIPPED_KINDS.has(kind) || !countries[cc] || !name) continue;
  const region = regions[`${cc}.${cols[10]}`] ?? '';
  const row = [name, region, cc, population];
  if (ascii && ascii !== name) row.push(ascii);
  rows.push(row);
}
rows.sort((a, b) => b[3] - a[3] || a[0].localeCompare(b[0]));

const built = new Date().toISOString().slice(0, 10);
writeFileSync(
  'public/data/world-cities.json',
  JSON.stringify({
    source: 'GeoNames cities15000 (https://www.geonames.org), CC BY 4.0',
    built,
    columns: ['name', 'region', 'countryCode', 'population', 'asciiName'],
    countries,
    cities: rows,
  })
);

const countryLines = Object.entries(countries)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, name]) => `  ${code}: ${JSON.stringify(name)},`)
  .join('\n');
writeFileSync(
  'src/data/countries.ts',
  `/**
 * LIFE SCORE - every country's English name by ISO 3166-1 alpha-2 code.
 *
 * Generated by scripts/build-world-cities.mjs from GeoNames countryInfo.txt
 * (https://www.geonames.org, CC BY 4.0) on ${built}. Do not edit by hand: rerun
 * the script. Used for flags and for the world city list's country names.
 */

export const COUNTRY_NAMES: Record<string, string> = {
${countryLines}
};
`
);

console.log(`${rows.length} cities, ${Object.keys(countries).length} countries -> public/data/world-cities.json, src/data/countries.ts`);
